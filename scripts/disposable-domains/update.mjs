#!/usr/bin/env node
/**
 * Refreshes the vendored disposable-email domain list from
 * github.com/disposable-email-domains/disposable-email-domains (CC0 1.0,
 * public domain) into
 * libraries/nestjs-libraries/src/database/prisma/subscriptions/disposable-email/domains.generated.ts.
 *
 *   node scripts/disposable-domains/update.mjs            # download and write
 *   node scripts/disposable-domains/update.mjs <file>     # from a local copy
 *
 * The app never fetches the list at run time: this script runs by hand or
 * from .github/workflows/disposable-domains.yml (weekly), which opens a pull
 * request with the change for review. It refuses a list that looks wrong
 * (too short, a line that is not a domain, a mainstream mailbox provider in
 * it), so a bad upstream commit cannot lock real people out.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE =
  'https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(
  ROOT,
  'libraries/nestjs-libraries/src/database/prisma/subscriptions/disposable-email/domains.generated.ts'
);
// Never in the list, whatever upstream says.
const MAINSTREAM = [
  'gmail.com', 'googlemail.com', 'yahoo.com', 'yahoo.co.in', 'outlook.com', 'hotmail.com',
  'live.com', 'icloud.com', 'me.com', 'proton.me', 'protonmail.com', 'zoho.com', 'aol.com',
  'gmx.com', 'mail.com', 'rediffmail.com', 'yandex.com', 'hookstep.in',
];
const DOMAIN = /^(?=.{3,253}$)([a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z0-9-]{2,63}$/;

export function parseList(text) {
  const domains = [...new Set(
    text.split(/\r?\n/).map((l) => l.trim().toLowerCase()).filter((l) => l && !l.startsWith('#'))
  )].sort();
  const bad = domains.filter((d) => !DOMAIN.test(d));
  if (bad.length) throw new Error(`not domains: ${bad.slice(0, 5).join(', ')}`);
  if (domains.length < 1000) throw new Error(`only ${domains.length} domains - refusing`);
  const mainstream = domains.filter((d) => MAINSTREAM.includes(d));
  if (mainstream.length) throw new Error(`mainstream providers in the list: ${mainstream.join(', ')}`);
  return domains;
}

export function render(domains, fetchedAt) {
  return `// GENERATED by scripts/disposable-domains/update.mjs - do not edit by hand.
// Source: github.com/disposable-email-domains/disposable-email-domains
// (disposable_email_blocklist.conf), CC0 1.0 public domain; see README.md
// next to this file. ${domains.length} domains, fetched ${fetchedAt}.
export const DISPOSABLE_DOMAINS_TEXT = ${JSON.stringify(domains.join('\n'))};
`;
}

async function main() {
  const local = process.argv[2];
  let text;
  if (local) {
    text = readFileSync(local, 'utf8');
  } else {
    const res = await fetch(SOURCE);
    if (!res.ok) throw new Error(`${SOURCE} answered ${res.status}`);
    text = await res.text();
  }
  const domains = parseList(text);
  writeFileSync(OUT, render(domains, new Date().toISOString().slice(0, 10)));
  console.log(`wrote ${domains.length} domains to ${OUT}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((e) => {
    console.error(`✗ ${e.message}`);
    process.exit(1);
  });
}
